// Command dokimi-mutate-go measures how well the tests of Go packages detect faults.
//
// dokimi-mutate-go --help writes this help:
//
//	Usage: dokimi-mutate-go [options] [PACKAGES...]
//
//	dokimi-mutate-go measures how well the tests of Go packages detect faults.
//
//	The command changes each package's code in small, defined ways, such as
//	a + b to a - b. Each change is a mutant. The command runs the package's
//	tests against each mutant, one at a time. A mutant that no test detects is a
//	gap in the tests. The command prints each such mutant at its file and line,
//	and a mutation score for each package.
//
//	The packages are patterns, as go list resolves them. The default is the
//	package in the current directory. The module under test needs no change:
//
//	  go run go.dokimi.dev/mutate/cmd/dokimi-mutate-go@latest ./...
//
//	Each option also reads the environment variable that its row names, and its
//	flag takes precedence over the variable.
//
//	--lines and --diff select the lines whose mutants the command tests. --lines
//	repeats, or takes entries that commas separate. --diff selects the lines
//	that a unified diff adds, and the lines on either side of each run of
//	removed lines. A path of either, after the b/ prefix of a diff, is relative
//	to the current directory. --diff - reads the diff from standard input.
//
//	--sample tests the first n mutants of each package in the order of their
//	keys, so the same code gives the same sample on every machine. The score is
//	the score of the sample.
//
//	--include-generated mutates every generated file. A generated file has a
//	comment line such as "// Code generated by stringer. DO NOT EDIT." before
//	its package clause. Without the flag, the command mutates such a file only
//	when the comments before its package clause contain the line
//	//dokimi:mutate-include.
//
//	--suite runs the tests of other packages against the mutants of each
//	package, where those tests import the package. --skip tests none of the
//	mutants of the packages that it names. The summary and the record of each
//	such package count its mutants as not selected.
//
//	--confirm tests each mutant that survived or that no test covers once more,
//	in a normal build that contains this mutant alone. Tests that skip in the
//	instrumented build, such as allocation checks, then run against it. Each
//	such mutant costs one more build.
//
//	--parallel above 1 counts the mutants of each package first, starts the
//	packages with the most mutants first, and gives each a share of the
//	command's GOMAXPROCS threads in proportion to its mutants. --workers tests
//	up to n mutants of one package at once, on the share of the package and on
//	the threads that other packages return. Tests that share a resource, such as
//	a fixed port, can then fail each other, and each such failure counts as a
//	detection.
//
//	--timeout starts a mutant only when the mutant can finish before the limit.
//	The mutants that do not start fail the run, and the summary states the score
//	of those that ran. The default, 0, turns the limit off.
//
//	--memory-budget takes K, M, G or T for powers of 1024. A mutant's run ends
//	when its test binary and the processes that the binary starts use more than
//	the binary's memory ceiling. The ceiling is at most the budget, and at least
//	the binary's peak without a mutant plus 512 MiB. A package tests as many
//	mutants at once as fit in the budget with their ceilings, and starts them
//	when they fit beside those of the running packages. The default is three
//	quarters of the memory that the process may use, by its cgroup or by the
//	machine. 0 turns the budget off, and the memory that the process may use
//	then bounds the ceilings.
//
//	The command prints each mutant that survived or that no test covers when its
//	verdict is final, and a summary when the run of a package ends:
//
//	  wire/codec.go:41:9: survived: n + 1 became n - 1 (aor)
//	  wire/codec.go:52:2: not covered: buf.Reset() removed (sbr-delete)
//	  example.com/wire: 410 of 432 mutants detected (94%): 405 killed, 5 timed out, 20 survived, 2 not covered
//
//	Progress lines and errors go to standard error.
//
//	Exit status:
//
//	  0  Every counted mutant was detected, and every run completed.
//	  1  A package has a mutant that survived or that no test covers, in its
//	     sample when --sample ended its run.
//	  2  The command line or an input is invalid.
//	  3  A run failed, such as a package that does not build, tests that fail
//	     without a mutant, or a run that --timeout ended. The command also
//	     exits with 3 when it cannot write to standard output.
//
//	A test can read two variables. DOKIMI_MUTATE_MUTANT is 0 in the control runs
//	and the active mutant's number in a mutant's run. DOKIMI_MUTATE_INSTRUMENTED
//	is 1 in every run of the instrumented build. Skip an allocation or timing
//	assertion while DOKIMI_MUTATE_INSTRUMENTED is set, and use --confirm.
//
//	Examples:
//
//	  dokimi-mutate-go ./...
//	  git diff origin/main...HEAD | dokimi-mutate-go --diff - ./...
//	  dokimi-mutate-go --workers 4 --timeout 30m --record out ./...
//	  dokimi-mutate-go --list ./wire
//
//	Arguments:
//	      PACKAGES  Patterns of the packages to test.  default "."
//
//	Options:
//	      --confirm             Test each undetected mutant once more in a normal build.                env DOKIMI_MUTATE_GO_CONFIRM
//	      --diff file           Unified diff of the lines to test, or - for standard input.             env DOKIMI_MUTATE_GO_DIFF
//	  -C, --directory string    Directory to change to before the command resolves paths.               env DOKIMI_MUTATE_GO_DIRECTORY
//	      --flag-debug          Print the value and the source of each option before the command runs.  env DOKIMI_MUTATE_GO_FLAG_DEBUG
//	  -h, --help                Show the help.
//	      --include-generated   Also mutate generated files.                                            env DOKIMI_MUTATE_GO_INCLUDE_GENERATED
//	      --json                Write the record of each package as one line of JSON.                   env DOKIMI_MUTATE_GO_JSON
//	      --lines lines,...     Lines to test, as file:first-last.                                      env DOKIMI_MUTATE_GO_LINES
//	      --list                List the mutants of each package instead of testing them.               env DOKIMI_MUTATE_GO_LIST
//	      --memory-budget size  Memory that the packages tested at once may use, such as 16G.           env DOKIMI_MUTATE_GO_MEMORY_BUDGET
//	  -p, --parallel int        Number of packages that may run at once.                                default "1", env DOKIMI_MUTATE_GO_PARALLEL
//	      --record string       Directory that receives the record of each package.                     env DOKIMI_MUTATE_GO_RECORD
//	      --sample int          Number of mutants to test in each package, the first by key.            env DOKIMI_MUTATE_GO_SAMPLE
//	      --skip string,...     Packages whose mutants the command does not test.                       env DOKIMI_MUTATE_GO_SKIP
//	      --suite string,...    Packages whose tests also run against the mutants.                      env DOKIMI_MUTATE_GO_SUITE
//	      --timeout duration    Time limit of the command, such as 30m.                                 env DOKIMI_MUTATE_GO_TIMEOUT
//	      --version             Show the version.
//	      --workers int         Most mutants of one package that may run at once.                       default "1", env DOKIMI_MUTATE_GO_WORKERS
