// paragraphWidth is the width of a paragraph of the help's text, in bytes.
const paragraphWidth = 76

// exampleIndent starts each line of an example in the help's text.
const exampleIndent = "  "

// tie joins two words of the help's text that no line break may separate,
// such as a number and its unit. The help writes it as a space.
const tie = "~"

// commandPath is the package path of the command.
const commandPath = record.Module + "/cmd/" + name

// summary is the first sentence of the help's text, and of the command's
// documentation.
const summary = name + " measures how well the tests of Go packages detect faults."

// gibibyte is the unit of the computed default of --memory-budget in the help.
const gibibyte = 1 << 30

// helpText returns the help text of the command. The text states what the
// command does and the mechanisms behind its options. It then shows the
// output, the exit statuses, the variables that a test reads and examples.
// The help lists the options after the text. note is a sentence on the
// default memory budget of this process, which the text adds to its
// paragraph on --memory-budget. The documentation passes the empty note, so
// it does not depend on the machine that writes it.
func helpText(note string) string {
	lines, diff, sample := flagPrefix+flagLines, flagPrefix+flagDiff, flagPrefix+flagSample
	timeout, confirm, workers := flagPrefix+flagTimeout, flagPrefix+flagConfirm, flagPrefix+flagWorkers
	var b strings.Builder
	paragraph(&b, summary)
	paragraph(&b, "The command changes each package's code in small, defined ways, such as a~+~b to a~-~b. Each "+
		"change is a mutant. The command runs the package's tests against each mutant, one at a time. A mutant "+
		"that no test detects is a gap in the tests. The command prints each such mutant at its file and line, "+
		"and a mutation score for each package.")
	paragraph(&b, "The packages are patterns, as go list resolves them. The default is the package in the "+
		"current directory. The module under test needs no change:")
	b.WriteString(exampleIndent + "go run " + commandPath + "@latest ./...\n\n")
	paragraph(&b, "Each option also reads the environment variable that its row names, and its flag takes "+
		"precedence over the variable.")
	paragraph(&b, lines+" and "+diff+" select the lines whose mutants the command tests. "+lines+" repeats, "+
		"or takes entries that commas separate. "+diff+" selects the lines that a unified diff adds, and the "+
		"lines on either side of each run of removed lines. A path of either, after the b/ prefix of a diff, is "+
		"relative to the current directory. "+diff+" "+stdinPath+" reads the diff from standard input.")
	paragraph(&b, sample+" tests the first n mutants of each package in the order of their keys, so the same "+
		"code gives the same sample on every machine. The score is the score of the sample.")
	paragraph(&b, flagPrefix+flagIncludeGenerated+" mutates every generated file. A generated file has a "+
		"comment line such as \"// Code generated by stringer. DO NOT EDIT.\" before its package clause. "+
		"Without the flag, the command mutates such a file only when the comments before its package clause "+
		"contain the line "+includeDirective+".")
	paragraph(&b, flagPrefix+flagSuite+" runs the tests of other packages against the mutants of each package, "+
		"where those tests import the package. "+flagPrefix+flagSkip+" tests none of the mutants of the "+
		"packages that it names. The summary and the record of each such package count its mutants as not "+
		"selected.")
	paragraph(&b, confirm+" tests each mutant that survived or that no test covers once more, in a normal "+
		"build that contains this mutant alone. Tests that skip in the instrumented build, such as allocation "+
		"checks, then run against it. Each such mutant costs one more build.")
	paragraph(&b, flagPrefix+flagParallel+" above 1 counts the mutants of each package first, starts the "+
		"packages with the most mutants first, and gives each a share of the command's GOMAXPROCS threads in "+
		"proportion to its mutants. "+workers+" tests up to n mutants of one package at once, on the share of "+
		"the package and on the threads that other packages return. Tests that share a resource, such as a "+
		"fixed port, can then fail each other, and each such failure counts as a detection.")
	paragraph(&b, timeout+" starts a mutant only when the mutant can finish before the limit. The mutants "+
		"that do not start fail the run, and the summary states the score of those that ran. The default, 0, "+
		"turns the limit off.")
	paragraph(&b, flagPrefix+flagBudget+" takes K, M, G or T for powers of 1024. A mutant's run ends when its "+
		"test binary and the processes that the binary starts use more than the binary's memory ceiling. The "+
		"ceiling is at most the budget, and at least the binary's peak without a mutant plus 512"+tie+"MiB. "+
		"A package tests as many mutants at once as fit in the budget with their ceilings, and starts them "+
		"when they fit beside those of the running packages. The default is three quarters of the memory that "+
		"the process may use, by its cgroup or by the machine. 0 turns the budget off, and the memory that the "+
		"process may use then bounds the ceilings. "+note)
	paragraph(&b, "The command prints each mutant that survived or that no test covers when its verdict is "+
		"final, and a summary when the run of a package ends:")
	b.WriteString(exampleIndent + "wire/codec.go:41:9: survived: n + 1 became n - 1 (aor)\n" +
		exampleIndent + "wire/codec.go:52:2: not covered: buf.Reset() removed (sbr-delete)\n" +
		exampleIndent + "example.com/wire: 410 of 432 mutants detected (94%): 405 killed, 5 timed out, " +
		"20 survived, 2 not covered\n\n")
	paragraph(&b, "Progress lines and errors go to standard error.")
	b.WriteString("Exit status:\n\n" +
		exampleIndent + "0  Every counted mutant was detected, and every run completed.\n" +
		exampleIndent + "1  A package has a mutant that survived or that no test covers, in its\n" +
		exampleIndent + "   sample when " + sample + " ended its run.\n" +
		exampleIndent + "2  The command line or an input is invalid.\n" +
		exampleIndent + "3  A run failed, such as a package that does not build, tests that fail\n" +
		exampleIndent + "   without a mutant, or a run that " + timeout + " ended. The command also\n" +
		exampleIndent + "   exits with 3 when it cannot write to standard output.\n\n")
	paragraph(&b, fmt.Sprintf("A test can read two variables. %s is 0 in the control runs and the active "+
		"mutant's number in a mutant's run. %s is 1 in every run of the instrumented build. Skip an allocation "+
		"or timing assertion while %[2]s is set, and use %s.",
		definition.Protocol.Variable, definition.Protocol.Instrumented, confirm))
	b.WriteString("Examples:\n\n" +
		exampleIndent + name + " ./...\n" +
		exampleIndent + "git diff origin/main...HEAD | " + name + " " + diff + " " + stdinPath + " ./...\n" +
		exampleIndent + name + " " + workers + " 4 " + timeout + " 30m " + flagPrefix + flagRecord + " out ./...\n" +
		exampleIndent + name + " " + flagPrefix + flagList + " ./wire")
	return b.String()
}

// budgetDefault returns the sentence that states the default of
// --memory-budget in this process, whose default budget is bytes.
func budgetDefault(bytes int64) string {
	if bytes == 0 {
		return "Here the default is 0, because no file states the memory that the process may use."
	}
	return fmt.Sprintf("Here the default is %.1f"+tie+"GiB.", float64(bytes)/gibibyte)
}

// versions returns the versions of the engine, of the operator catalogue, of
// the Go overlay and of the toolchain that built the engine, one on each
// line after its name.
func versions() string {
	info, _ := debug.ReadBuildInfo()
	return fmt.Sprintf("%s %s\ncatalogue %s\noverlay %s\ntoolchain %s",
		name, record.EngineVersion(info), definition.Version, definition.Overlay.Version, runtime.Version())
}

// paragraph writes text to b as a paragraph of lines of at most
// paragraphWidth bytes, and a blank line after it.
func paragraph(b *strings.Builder, text string) {
	wrap(b, text, "", paragraphWidth)
	b.WriteString("\n")
}

// wrap writes text to b as lines of at most width bytes after indent,
// broken at its spaces, with each tie written as a space. Words that ties
// join, and a word longer than width, take a line of their own when they
// do not fit.
func wrap(b *strings.Builder, text, indent string, width int) {
	line := ""
	for word := range strings.FieldsSeq(text) {
		if line != "" && len(line)+1+len(word) > width {
			b.WriteString(indent + strings.ReplaceAll(line, tie, " ") + "\n")
			line = ""
		}
		if line != "" {
			line += " "
		}
		line += word
	}
	b.WriteString(indent + strings.ReplaceAll(line, tie, " ") + "\n")
}
